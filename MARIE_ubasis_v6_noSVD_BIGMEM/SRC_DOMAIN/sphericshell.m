function [idx] = sphericshell(r,c,innR,extR)
%
% _________________________________________________________________________
% _________________________________________________________________________
%
%   Function that generates a region in a cylindric shell
%
% _________________________________________________________________________
% _________________________________________________________________________
%
%

sphereshell = @(r)( (r(:,:,:,1) - c(1,1) ).^2 + ( r(:,:,:,2) - c(2,1) ).^2 + ( r(:,:,:,3) - c(3,1) ).^2 > (innR)^2 ) & ( (r(:,:,:,1) - c(1,1) ).^2 + ( r(:,:,:,2) - c(2,1) ).^2 + ( r(:,:,:,3) - c(3,1) ).^2 < (extR)^2) ;
pointsI= sphereshell(r); % ones for domain elements in the shell
idx = find(pointsI(:)); % get indexes of elements
